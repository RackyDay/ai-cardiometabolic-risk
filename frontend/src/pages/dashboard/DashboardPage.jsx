import { useState } from "react";

import {
  LineChart,
  Line,
  XAxis,
  YAxis,
  Tooltip,
  ResponsiveContainer,
  CartesianGrid,
} from "recharts";

// import EyeIcon from "../../components/icons/EyeIcon";
import AlertTriangleIcon from "../../components/icons/AlertTriangleIcon";
import RiskGauge from "./components/RiskGauge";

import RiskFactorPieChart, {
  getRiskFactorColor,
  RISK_FACTOR_DESCRIPTIONS,
} from "./components/RiskFactorPieChart";

import { useDashboardViewModel } from "./useDashboardViewModel";

import "./DashboardPage.css";


const VISIBLE_RISK_FACTOR_ROWS = 5;


const INSIGHTS = [
  "Overall Risk Score has decreased by 4%",
  "Heart rate has improved by 5 BPM",
  "BMI result is now closer to the ideal value",
];

// Tempoorary
const TREND_DATA = [
  { year: 1, risk: 35 },
  { year: 2, risk: 92 },
  { year: 3, risk: 80 },
  { year: 4, risk: 95 },
  { year: 5, risk: 40 },
  { year: 6, risk: 78 },
  { year: 7, risk: 60 },
  { year: 8, risk: 8 },
  { year: 9, risk: 42 },
  { year: 10, risk: 68 },
];


const RISK_SCORE_DISCLAIMER =
  "This score is an estimate generated by a predictive model, not a medical diagnosis. Speak to a healthcare provider for personalised advice.";


/* =========================================================
   Slider for numerical risk factors
========================================================= */

function RiskFactorSlider({
  factor,
  value,
  config,
  onChange,
}) {
  const numericValue =
    value === null ||
    value === undefined
      ? config.min
      : Number(value);

  return (
    <div className="what-if-control">

      <div className="what-if-value-row">

        <span>
          Current
        </span>

        <strong>
          {numericValue}

          {config.unit
            ? ` ${config.unit}`
            : ""}
        </strong>

      </div>


      <input
        type="range"

        min={config.min}

        max={config.max}

        step={config.step}

        value={numericValue}

        onChange={(event) =>
          onChange(
            factor.feature,
            Number(
              event.target.value
            )
          )
        }

        className="what-if-slider"

        aria-label={`Change ${factor.label}`}
      />


      <div className="what-if-range">

        <span>
          {config.min}

          {config.unit
            ? ` ${config.unit}`
            : ""}
        </span>

        <span>
          {config.max}

          {config.unit
            ? ` ${config.unit}`
            : ""}
        </span>

      </div>

    </div>
  );
}


/* =========================================================
   Toggle for binary risk factors
========================================================= */

function RiskFactorToggle({
  factor,
  value,
  onChange,
}) {
  const enabled = Boolean(value);

  return (
    <div className="what-if-control">

      <div className="what-if-toggle-row">

        <span>
          {enabled
            ? "Currently enabled"
            : "Currently disabled"}
        </span>


        <button
          type="button"

          className={`what-if-toggle ${
            enabled
              ? "what-if-toggle-on"
              : ""
          }`}

          onClick={() =>
            onChange(
              factor.feature,
              !enabled
            )
          }

          aria-pressed={enabled}

          aria-label={`Change ${factor.label}`}
        >

          <span className="what-if-toggle-track">

            <span className="what-if-toggle-thumb" />

          </span>


          <span className="what-if-toggle-label">

            {enabled
              ? "Yes"
              : "No"}

          </span>

        </button>

      </div>

    </div>
  );
}


/* =========================================================
   Dashboard
========================================================= */

function DashboardPage() {

  const {
    displayScore,
    riskFactors,
    pieData,

    originalInputs,

    hypotheticalScore,
    hypotheticalInputs,
    hypotheticalPieData,

    changeableRiskFactors,

    updateHypotheticalInput,
    resetHypothetical,

    isHypotheticalActive,

  } = useDashboardViewModel();


  const [
    showDisclaimer,
    setShowDisclaimer,
  ] = useState(false);


  const [
    isInsightsOpen,
    setIsInsightsOpen,
  ] = useState(false);


  /*
   * Only one changeable risk factor can be
   * expanded at a time.
   */
  const [
    expandedFactor,
    setExpandedFactor,
  ] = useState(null);


  return (
    <div className="dashboard-page">


      {/* =====================================================
          RISK SCORE + INSIGHTS
      ====================================================== */}

      <div className="top-row">


        {/* ===================================================
            RISK SCORE
        ==================================================== */}

        <div className="card risk-score-card">

          <div className="card-header-row">

            <h2 className="card-title">
              Risk Score
            </h2>


            <div className="disclaimer-wrapper">

              <button
                type="button"

                className="disclaimer-trigger"

                onClick={() =>
                  setShowDisclaimer(
                    (prev) => !prev
                  )
                }

                aria-expanded={
                  showDisclaimer
                }

                aria-label="Risk score disclaimer"
              >

                <AlertTriangleIcon
                  size={18}
                  color="#d97706"
                />

              </button>


              <div
                className={`disclaimer-panel ${
                  showDisclaimer
                    ? "open"
                    : ""
                }`}
              >

                <p className="disclaimer-title">
                  Disclaimer
                </p>


                <p className="disclaimer-text">
                  {RISK_SCORE_DISCLAIMER}
                </p>

              </div>

            </div>

          </div>


          <div className="gauge-center">

            <RiskGauge

              score={
                isHypotheticalActive &&
                hypotheticalScore !== null
                  ? hypotheticalScore
                  : displayScore
              }

            />

          </div>

        </div>


      {/* =====================================================
          MERGED RISK FACTOR BREAKDOWN
      ====================================================== */}

      <div className="card risk-breakdown-card">


        {/* ===================================================
            HEADER
        ==================================================== */}

        <div className="risk-breakdown-header">

          <div>

            <h2 className="card-title">
              Risk Factor Breakdown
            </h2>


            <p className="risk-chart-description">

              {isHypotheticalActive

                ? "Showing the estimated contribution of each factor after your changes."

                : "Relative contribution of the factors used in your current risk assessment."}

            </p>

          </div>

        </div>


        {/* ===================================================
            PIE CHART
        ==================================================== */}

        <RiskFactorPieChart

          data={pieData}

          hypotheticalData={
            hypotheticalPieData
          }

          isHypotheticalActive={
            isHypotheticalActive
          }

        />


        {/* ===================================================
            RISK FACTOR LIST
        ==================================================== */}

        {riskFactors.length > 0 && (

          <div className="risk-breakdown-controls">


            <div className="risk-breakdown-controls-header">

              <span>
                Risk factor
              </span>


              <span>
                Contribution
              </span>

            </div>


            <div
              className="risk-factor-list merged-risk-factor-list"

              style={{
                "--visible-rows":
                  VISIBLE_RISK_FACTOR_ROWS,
              }}
            >

              {riskFactors.map(
                (factor, i) => {

                  /* -----------------------------------------
                     Determine whether factor is changeable
                  ------------------------------------------ */

                  const config =
                    changeableRiskFactors[
                      factor.feature
                    ];


                  const isChangeable =
                    Boolean(config);


                  /* -----------------------------------------
                     Map backend feature names
                     to frontend schema names
                  ------------------------------------------ */

                  const schemaKey =
                    factor.feature ===
                    "male"

                      ? "gender"

                      : factor.feature ===
                        "BPMeds"

                      ? "bpMeds"

                      : factor.feature;


                  /* -----------------------------------------
                     Current value
                  ------------------------------------------ */

                  const currentValue =
                    hypotheticalInputs?.[
                      schemaKey
                    ] ??
                    originalInputs?.[
                      schemaKey
                    ] ??
                    null;


                  /* -----------------------------------------
                     Expansion state
                  ------------------------------------------ */

                  const isExpanded =
                    expandedFactor ===
                    factor.feature;


                  return (

                    <div

                      key={
                        factor.feature
                      }

                      className={`merged-risk-factor-item ${
                        isChangeable
                          ? "merged-risk-factor-changeable"
                          : "merged-risk-factor-fixed"
                      } ${
                        isExpanded
                          ? "merged-risk-factor-expanded"
                          : ""
                      }`}

                    >


                      {/* =====================================
                          MAIN FACTOR ROW
                      ====================================== */}

                      <div className="risk-factor-row">


                        {/* Number */}

                        <span className="risk-factor-number">

                          {i + 1}.

                        </span>


                        {/* Pie chart colour */}

                        <span

                          className="risk-factor-color"

                          style={{
                            backgroundColor:
                              getRiskFactorColor(
                                factor.label,
                                i
                              ),
                          }}

                        />


                        {/* Name */}

                        <span

                          className="risk-factor-label"

                          title={
                            factor.label
                          }

                        >

                          {factor.label}

                        </span>


                        {/* Contribution */}

                        <span

                          className={`risk-factor-tag ${
                            factor.raisesRisk
                              ? "risk-factor-tag-up"
                              : "risk-factor-tag-down"
                          }`}

                        >

                          {factor.raisesRisk
                            ? "+"
                            : "-"}

                          {Math.round(
                            factor.weightPercent
                          )}

                          %

                        </span>


                        {/* Fixed label */}

                        {!isChangeable && (

                          <span className="risk-factor-locked">

                            Fixed

                          </span>

                        )}


                        {/* =================================
                            DROPDOWN FOR CHANGEABLE FACTORS
                        ================================== */}

                        {isChangeable && (

                          <button

                            type="button"

                            className="risk-factor-expand-button"

                            aria-label={
                              isExpanded
                                ? `Collapse ${factor.label}`
                                : `Expand ${factor.label}`
                            }

                            aria-expanded={
                              isExpanded
                            }

                            onClick={() =>
                              setExpandedFactor(
                                (current) =>
                                  current ===
                                  factor.feature
                                    ? null
                                    : factor.feature
                              )
                            }

                          >

                            <span

                              className={`risk-factor-chevron ${
                                isExpanded
                                  ? "risk-factor-chevron-open"
                                  : ""
                              }`}

                            >

                              ▼

                            </span>

                          </button>

                        )}

                      </div>


                      {/* =====================================
                          NON-CHANGEABLE FACTOR DESCRIPTION

                          Appears only when hovering
                      ====================================== */}

                      {!isChangeable && (

                        <div className="fixed-factor-description">

                          <span className="risk-factor-description-label">

                            Why it matters:

                          </span>


                          <span className="risk-factor-description-text">

                            {RISK_FACTOR_DESCRIPTIONS[
                              factor.label
                            ] ||
                              "This factor is included by the risk model because it can provide information relevant to cardiovascular risk."}

                          </span>

                        </div>

                      )}


                      {/* =====================================
                          CHANGEABLE FACTOR CONTENT

                          Only visible when dropdown
                          is opened.
                      ====================================== */}

                      {isChangeable &&
                        isExpanded && (

                          <div className="risk-factor-expanded-content">


                            {/* =================================
                                WHY IT MATTERS
                            ================================== */}

                            <div className="risk-factor-description">

                              <span className="risk-factor-description-label">

                                Why it matters:

                              </span>


                              <span className="risk-factor-description-text">

                                {RISK_FACTOR_DESCRIPTIONS[
                                  factor.label
                                ] ||
                                  "This factor is included by the risk model because it can provide information relevant to cardiovascular risk."}

                              </span>

                            </div>


                            {/* =================================
                                WHAT-IF CONTROL
                            ================================== */}

                            <div className="what-if-section">

                              <div className="what-if-heading">

                                <span>
                                  What-if adjustment
                                </span>


                                <span className="what-if-badge">

                                  Changeable

                                </span>

                              </div>


                              {config.type ===
                                "slider" && (

                                <RiskFactorSlider

                                  factor={
                                    factor
                                  }

                                  value={
                                    currentValue
                                  }

                                  config={
                                    config
                                  }

                                  onChange={
                                    updateHypotheticalInput
                                  }

                                />

                              )}


                              {config.type ===
                                "toggle" && (

                                <RiskFactorToggle

                                  factor={
                                    factor
                                  }

                                  value={
                                    currentValue
                                  }

                                  onChange={
                                    updateHypotheticalInput
                                  }

                                />

                              )}

                            </div>

                          </div>

                        )}

                    </div>

                  );

                }
              )}

            </div>

          </div>

        )}


        {/* ===================================================
            WHAT-IF SUMMARY
        ==================================================== */}

        {isHypotheticalActive &&
          hypotheticalScore !== null &&
          hypotheticalScore !== undefined && (

            <div className="what-if-summary">


              <div className="what-if-summary-header">

                <div>

                  <span className="what-if-summary-label">

                    What-if scenario

                  </span>


                  <span className="what-if-summary-description">

                    Your original assessment
                    remains unchanged.

                  </span>

                </div>


                <button

                  type="button"

                  className="what-if-reset-button"

                  onClick={
                    resetHypothetical
                  }

                >

                  Reset

                </button>

              </div>


              <div className="what-if-score-row">


                <div className="what-if-score">

                  <span>
                    Original
                  </span>


                  <strong>

                    {Number(
                      displayScore
                    ).toFixed(1)}

                    %

                  </strong>

                </div>


                <div className="what-if-arrow">

                  →

                </div>


                <div className="what-if-score">

                  <span>
                    What-if
                  </span>


                  <strong>

                    {Number(
                      hypotheticalScore
                    ).toFixed(1)}

                    %

                  </strong>

                </div>


                <div

                  className={`what-if-difference ${
                    hypotheticalScore <
                    displayScore

                      ? "what-if-improved"

                      : hypotheticalScore >
                        displayScore

                      ? "what-if-increased"

                      : ""
                  }`}

                >

                  {hypotheticalScore <
                  displayScore

                    ? `${(
                        displayScore -
                        hypotheticalScore
                      ).toFixed(
                        1
                      )}% lower`

                    : hypotheticalScore >
                      displayScore

                    ? `${(
                        hypotheticalScore -
                        displayScore
                      ).toFixed(
                        1
                      )}% higher`

                    : "No change"}

                </div>

              </div>

            </div>

          )}

      </div>

      {/* ===================================================
            INSIGHTS
        ==================================================== */}

        <div className="card insights-card">

          <h2 className="card-title">
            Insights
          </h2>


          <p className="insight-subheading">
            Since the last assessment:
          </p>


          <div className="insight-list">

            {INSIGHTS.map(
              (text, i) => (

                <div
                  key={i}
                  className="insight-item insight-green"
                >

                  {text}

                </div>

              )
            )}

          </div>


          <p className="insight-subheading stress-heading">
            Stress
          </p>


          <div className="insight-item insight-red">

            Your data shows traits that
            are usually associated with
            stress. This could suggest
            that you may be experiencing
            high stress.

          </div>

        </div>

      </div>


      {/* =====================================================
          10-YEAR CARDIOVASCULAR HEALTH TREND
      ====================================================== */}

      <div className="card trend-card">
        <h2 className="card-title">

          10-year Cardiovascular Health Trend

        </h2>


        <ResponsiveContainer
          width="100%"
          height={260}
        >

          <LineChart

            data={TREND_DATA}

            margin={{
              top: 10,
              right: 20,
              left: 0,
              bottom: 10,
            }}

          >

            <CartesianGrid

              strokeDasharray="3 3"

              stroke="#e5e7eb"

              vertical={true}

            />


            <XAxis

              dataKey="year"

              label={{
                value: "Year",
                position:
                  "insideBottom",
                offset: -4,
                fontSize: 13,
                fill: "#6b7280",
              }}

              tick={{
                fontSize: 12,
                fill: "#6b7280",
              }}

              tickLine={false}

              axisLine={false}

            />


            <YAxis

              domain={[
                0,
                100,
              ]}

              ticks={[
                0,
                25,
                50,
                75,
                100,
              ]}

              label={{
                value: "Risk score",
                angle: -90,
                position:
                  "insideLeft",
                offset: 10,
                fontSize: 13,
                fill: "#6b7280",
              }}

              tick={{
                fontSize: 12,
                fill: "#6b7280",
              }}

              tickLine={false}

              axisLine={false}

            />


            <Tooltip

              contentStyle={{
                borderRadius: 8,
                border:
                  "1px solid #e5e7eb",
                fontSize: 13,
              }}

              formatter={(value) => [
                `${value}`,
                "Risk Score",
              ]}

              labelFormatter={(label) =>
                `Year ${label}`
              }

            />


            <Line

              type="monotone"

              dataKey="risk"

              stroke="#3b82f6"

              strokeWidth={2.5}

              dot={{
                r: 4,
                fill: "#3b82f6",
                strokeWidth: 0,
              }}

              activeDot={{
                r: 6,
              }}

            />

          </LineChart>

        </ResponsiveContainer>

      </div>


      {/* =====================================================
          INSIGHTS MODAL
      ====================================================== */}

      {isInsightsOpen && (

        <div

          className="insight-modal-backdrop"

          onClick={() =>
            setIsInsightsOpen(false)
          }

        >

          <div

            className="insight-modal"

            onClick={(event) =>
              event.stopPropagation()
            }

          >

            <div className="insight-modal-header">

              <h2 className="card-title">
                Insights
              </h2>


              <button

                className="insight-modal-close"

                aria-label="Close insights"

                onClick={() =>
                  setIsInsightsOpen(false)
                }

              >

                ×

              </button>

            </div>


            <p className="insight-subheading">

              Since the last assessment:

            </p>


            <div className="insight-list">

              {INSIGHTS.map(
                (text, i) => (

                  <div

                    key={i}

                    className="insight-item insight-green"

                  >

                    {text}

                  </div>

                )
              )}

            </div>


            <p className="insight-subheading stress-heading">

              Stress

            </p>


            <div className="insight-item insight-red">

              Your data shows traits that
              are usually associated with
              stress. This could suggest
              that you may be experiencing
              high stress.

            </div>

          </div>

        </div>

      )}

    </div>
  );
}


export default DashboardPage;