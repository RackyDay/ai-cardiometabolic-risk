/* =========================================================
   Slider
========================================================= */

function RiskFactorSlider({
  factor,
  value,
  config,
  onChange,
}) {

  const { clinicalUnit } =
    useContext(UnitContext);

  const numericValue =
    value === null ||
    value === undefined
      ? config.min
      : Number(value);

  // The slider itself always works in canonical mg/dL (that's what the
  // what-if prediction consumes); only the labels are shown in the
  // app-wide unit.
  const schemaField =
    riskInputSchema[factor.feature];

  const conversionFactor =
    schemaField?.mmolConversionFactor;

  const displayUnit =
    conversionFactor
      ? clinicalUnit
      : config.unit;

  const toDisplay = (canonical) =>
    canonicalToDisplay(
      canonical,
      displayUnit,
      conversionFactor
    );


  return (
    <div className="what-if-control">

      <div className="what-if-value-row">

        <span>
          Current
        </span>

        <strong>
          {toDisplay(numericValue)}

          {displayUnit
            ? ` ${displayUnit}`
            : ""}
        </strong>

      </div>


      <input
        type="range"

        min={config.min}
        max={config.max}
        step={config.step}

        value={numericValue}

        onChange={(event) =>
          onChange(
            factor.feature,
            Number(
              event.target.value
            )
          )
        }

        className="what-if-slider"

        aria-label={`Change ${factor.label}`}
      />


      <div className="what-if-range">

        <span>
          {toDisplay(config.min)}

          {displayUnit
            ? ` ${displayUnit}`
            : ""}
        </span>

        <span>
          {toDisplay(config.max)}

          {displayUnit
            ? ` ${displayUnit}`
            : ""}
        </span>

      </div>

    </div>
  );
}


/* =========================================================
   Toggle
========================================================= */

function RiskFactorToggle({
  factor,
  value,
  onChange,
}) {

  const enabled =
    Boolean(value);


  return (
    <div className="what-if-control">

      <div className="what-if-toggle-row">

        <span>
          {enabled
            ? "Currently enabled"
            : "Currently disabled"}
        </span>


        <button
          type="button"

          className={`what-if-toggle ${
            enabled
              ? "what-if-toggle-on"
              : ""
          }`}

          onClick={() =>
            onChange(
              factor.feature,
              !enabled
            )
          }

          aria-pressed={
            enabled
          }

          aria-label={`Change ${factor.label}`}
        >

          <span className="what-if-toggle-track">

            <span className="what-if-toggle-thumb" />

          </span>


          <span className="what-if-toggle-label">

            {enabled
              ? "Yes"
              : "No"}

          </span>

        </button>

      </div>

    </div>
  );
}


