/* =========================================================
   Helpers
========================================================= */

function formatValue(value, unit = "") {
  if (value === null || value === undefined || value === "") {
    return "Not available";
  }

  const number = Number(value);

  if (!Number.isFinite(number)) {
    return String(value);
  }

  const formatted =
    Number.isInteger(number)
      ? String(number)
      : number.toFixed(1);

  return unit
    ? `${formatted} ${unit}`
    : formatted;
}


/* =========================================================
   Slider
========================================================= */

function RiskFactorSlider({
  factor,
  originalValue,
  hypotheticalValue,
  config,
  onChange,
}) {
  const sliderValue =
    hypotheticalValue === null ||
    hypotheticalValue === undefined
      ? config.min
      : Number(hypotheticalValue);

  return (
    <div className="what-if-control">

      {/* Original value */}

      <div className="risk-value-comparison">

        <div className="risk-value-box">

          <span className="risk-value-label">
            Current value
          </span>

          <strong className="risk-value-current">
            {formatValue(
              originalValue,
              config.unit
            )}
          </strong>

        </div>


        <div className="risk-value-arrow">
          →
        </div>


        <div className="risk-value-box">

          <span className="risk-value-label">
            What-if value
          </span>

          <strong className="risk-value-hypothetical">
            {formatValue(
              sliderValue,
              config.unit
            )}
          </strong>

        </div>

      </div>


      {/* Slider */}

      <div className="what-if-slider-wrapper">

        <input
          type="range"
          min={config.min}
          max={config.max}
          step={config.step}
          value={sliderValue}
          onChange={(event) =>
            onChange(
              factor.feature,
              Number(event.target.value)
            )
          }
          className="what-if-slider"
          aria-label={`Adjust hypothetical ${factor.label}`}
        />

        <div className="what-if-range">

          <span>
            {formatValue(
              config.min,
              config.unit
            )}
          </span>

          <span>
            {formatValue(
              config.max,
              config.unit
            )}
          </span>

        </div>

      </div>

    </div>
  );
}


/* =========================================================
   Toggle
========================================================= */

function RiskFactorToggle({
  factor,
  originalValue,
  hypotheticalValue,
  onChange,
}) {
  const enabled = Boolean(hypotheticalValue);
  const originalEnabled = Boolean(originalValue);

  return (
    <div className="what-if-control">

      <div className="toggle-comparison">

        <div className="toggle-status">

          <span className="risk-value-label">
            Current status
          </span>

          <strong>
            {originalEnabled
              ? "Yes"
              : "No"}
          </strong>

        </div>


        <div className="risk-value-arrow">
          →
        </div>


        <div className="toggle-status">

          <span className="risk-value-label">
            What-if status
          </span>

          <button
            type="button"
            className={`what-if-toggle ${
              enabled
                ? "what-if-toggle-on"
                : ""
            }`}
            onClick={() =>
              onChange(
                factor.feature,
                !enabled
              )
            }
            aria-pressed={enabled}
            aria-label={`Change hypothetical ${factor.label}`}
          >

            <span className="what-if-toggle-track">
              <span className="what-if-toggle-thumb" />
            </span>

            <span className="what-if-toggle-label">
              {enabled ? "Yes" : "No"}
            </span>

          </button>

        </div>

      </div>

    </div>
  );
}


